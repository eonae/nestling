import type { Dispatch } from './dispatch.js';

import type { Token } from '@nestling/container';

/**
 * Токен транспорта: уточнение kernel-типа `TransportRef` до `ITransport`.
 *
 * Транспортный пакет объявляет свой токен именно так; декларации ссылаются
 * на транспорт этим значением, а `App` резолвит по нему инстанс из графа.
 */
export type TransportToken = Token<ITransport>;

/**
 * Базовый интерфейс транспорта.
 *
 * Способностей здесь нет: формы io — данные **объявления**
 * (`TransportDeclaration.capabilities`), потому что проверка форм идёт на
 * фазе ASSEMBLE, где экземпляров ещё нет.
 */
export interface ITransport {
  /**
   * Начинает приём запросов этим транспортом.
   *
   * Единственный вход: нульарного `listen()` и точки регистрации отдельного
   * endpoint'а в операции нет. Всё, чем транспорт обслуживает запросы,
   * передаётся `dispatch`'ем — а он существует только с фазы WIRE, поэтому
   * «начать принимать запросы при захвате» бесполезно: маршрутизировать
   * было бы нечего.
   *
   * @param dispatch - Маршруты этого транспорта и исполнение endpoint'а
   * @param signal - Канал остановки: взвод означает «новые запросы не
   * принимаются, in-flight отменяются кооперативно»
   */
  serve(dispatch: Dispatch, signal: AbortSignal): Promise<void>;

  /**
   * Останавливает транспорт (дренаж соединений с таймаутом).
   *
   * Второй канал остановки рядом с `signal`: сигнал отменяет работу,
   * `close()` отпускает ресурсы.
   */
  close?(): Promise<void>;
}
