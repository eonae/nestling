/**
 * Конфиг-секция инфра-модуля логирования.
 *
 * Секцию объявляет тот, кто её читает: токен наружу не уезжает (из
 * `./index.ts` экспортируется только `.keys`), поэтому инжектнуть секцию из
 * соседней фичи попросту нечем — это keys-capability, а не договорённость.
 *
 * Уровень живёт здесь, а не в параметре `logging({ … })`, по границе из
 * канона: параметр модуля — решение композиции (что существует в графе),
 * секция — решение среды (что можно поменять, не пересобирая образ).
 */

import { makeConfig } from '@nestling/config';
import { z } from 'zod';

/** `LOG_LEVEL` — единственный ключ секции; имя выведено из префикса */
export const LoggerConfig = makeConfig('log', {
  level: z.enum(['debug', 'info', 'error']).default('info'),
});

/** Право привязки источника — единственное, что уезжает наружу */
export const loggerConfigKeys = LoggerConfig.keys;
