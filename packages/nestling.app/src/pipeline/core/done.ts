/**
 * Досрочный успех: третий исход pre-юнита.
 *
 * Pre-юнит завершается добавкой к контексту, отказом или досрочным
 * успехом. Досрочный успех приходит значением `done()`: следующие
 * pre-юниты и хендлер не вызываются, ответная фаза начинается с успеха
 * без значения.
 *
 * Канал общий и про пайплайн, а не про конкретную задачу: ни ключа, ни
 * хранилища, ни повтора в нём нет. Слой дедупликации строится поверх
 * него, как любой другой слой.
 */

/**
 * Symbol-метка досрочного успеха.
 *
 * Отличает значение и от отказа, и от добавки к контексту: у отказа
 * дискриминант `isFail`, а добавка — обычный объект со строковыми
 * ключами.
 */
const DONE_BRAND = Symbol.for('nestling:done');

/** Значение досрочного успеха; создаётся только функцией {@link done} */
export interface Done {
  readonly [DONE_BRAND]: true;
}

/** Единственный экземпляр: значения в нём нет, различать нечего */
const DONE: Done = Object.freeze({ [DONE_BRAND]: true } as Done);

/**
 * Завершает endpoint успехом, не доходя до хендлера.
 *
 * Юнит подключается с признаком `{ done: true }`: без него возврат
 * `done()` роняет запрос ошибкой. Декларация обязана быть без `output` —
 * значения досрочный успех не несёт.
 *
 * @example
 * ```typescript
 * const layer = makePipeline().pre(
 *   async (ctx) => (await seen(ctx) ? done() : undefined),
 *   { done: true },
 * );
 * ```
 */
export function done(): Done {
  return DONE;
}

/**
 * Проверяет, что значение — досрочный успех.
 *
 * Рантайм пайплайна вызывает предикат перед `isFail` и до записи
 * результата в контекст.
 */
export function isDone(value: unknown): value is Done {
  return (
    typeof value === 'object' &&
    value !== null &&
    (value as Record<symbol, unknown>)[DONE_BRAND] === true
  );
}
