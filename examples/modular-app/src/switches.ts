/**
 * Переключатели состава приложения.
 *
 * Лежат отдельным файлом: значение читает и корень (в `switches:`), и
 * фича (в `providers:`), а корень импортирует фичу — не наоборот.
 */

import { makeSwitch } from '@nestlingjs/container';

/**
 * Чем отправлять письма.
 *
 * Значение приходит аргументом сборки — `APP_MAIL`. Обе ветки видны
 * статически, и в графе оказывается ровно одна: невыбранный адаптер не
 * создаётся и его зависимости не разрешаются.
 */
export const Mail = makeSwitch('mail', ['log', 'smtp'], { default: 'log' });
