/**
 * Конфиг-секция модуля логирования.
 *
 * Секцию объявляет тот, кто её читает. Наружу (`./index.ts`) уходит только
 * `.keys`, поэтому инжектировать секцию из другой фичи невозможно.
 *
 * Уровень логирования живёт в секции, а не в параметре `logging({ … })`:
 * параметр модуля — решение композиции (что есть в графе), секция —
 * решение среды (что меняется без пересборки).
 */

import { makeConfig } from '@nestling/config';
import { z } from 'zod';

/** `LOG_LEVEL` — единственный ключ секции; имя выведено из префикса */
export const LoggerConfig = makeConfig('log', {
  level: z.enum(['debug', 'info', 'error']).default('info'),
});

/** Право привязать источник: единственное, что экспортируется наружу */
export const loggerConfigKeys = LoggerConfig.keys;
