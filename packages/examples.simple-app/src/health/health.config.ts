import { from, makeConfig } from '@nestling/config';
import { z } from 'zod';

/**
 * Секция здоровья — **второй читатель** ключа `DATABASE_URL`.
 *
 * Ключ объявлен без разрешения и без ведома первого читателя: право читать
 * ключ не означает владения им. Схема здесь своя и намеренно другая — не
 * `z.url()`, а обычная строка: каждая секция валидирует сырое значение
 * независимо, и «валидации один раз на всех» в модели нет.
 *
 * `secret()` тут нет — и он не нужен: `app` уже пометил этот ключ, а
 * секретность считается объединением по всем объявленным читателям.
 * Печать этой секции редактируется наравне с печатью `app`.
 *
 * Разойтись двум читателям можно ровно в одном — во флаге `reloadable`:
 * объяви эту секцию `makeConfig.reloadable`, и сборка упадёт
 * `ConfigSharedKeyError`, назвав ключ, обе секции и обе починки.
 */
export const HealthConfig = makeConfig('health', {
  databaseUrl: from('DATABASE_URL', z.string()),
});
