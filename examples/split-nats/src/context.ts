/**
 * Арендатор, от имени которого выполняется запрос.
 *
 * `propagate: true` включает передачу значения через границу порта:
 * вызыватель берёт его из контекста текущего запроса и кладёт в конверт
 * сообщения, а реализация на другой стороне возвращает его в контекст
 * юнитом `TenantId.propagated()`. Так значение проходит через любое число
 * процессов, не появляясь ни в одной схеме `input`.
 */

import { contextVar } from '@nestling/pipeline';

export const TenantId = contextVar<string>()('tenantId', { propagate: true });
