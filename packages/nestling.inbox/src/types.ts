/**
 * Отметка приёма и интерфейс её хранилища.
 *
 * Хранилище — единственное место, которым пакет касается базы данных, и
 * поставляет его приложение. Драйвера здесь нет: отметка и бизнес-запись
 * обязаны коммититься одной транзакцией, поэтому они живут на одном
 * соединении, а соединение везёт приложение.
 */

/**
 * Отметка приёма: одно сообщение, обработанное одним потребителем.
 *
 * Ключ составной — потребитель и ключ идемпотентности. Одно событие
 * уходит нескольким подписчикам с одним ключом, и каждый дедуплицирует
 * его отдельно.
 */
export interface InboxMark {
  /**
   * Потребитель: паттерн endpoint'а (`ctx.raw.pattern`).
   *
   * У подписчика события это `<операция>@<подписчик>`, у реализации
   * команды — имя операции.
   */
  readonly consumer: string;

  /** Ключ идемпотентности сообщения из конверта */
  readonly key: string;

  /** Момент постановки отметки, epoch-миллисекунды */
  readonly receivedAt: number;
}

/** Исход попытки отметить сообщение обработанным */
export type InboxClaim =
  /** Отметка поставлена: сообщение видят впервые */
  | 'claimed'
  /** Отметка уже была: это повтор */
  | 'duplicate';

/** Аргументы одного прохода уборщика */
export interface InboxSweepOptions {
  /** Удалять отметки старше этого момента, epoch-миллисекунды */
  readonly olderThan: number;

  /** Сколько отметок удалить максимум за проход */
  readonly limit: number;
}

/**
 * Хранилище отметок приёма. Адаптер поставляет приложение под своим
 * DI-токеном, который принимает плагин полем `store`.
 *
 * Две операции покрывают весь жизненный цикл отметки: `claim` ставит её
 * транзакцией вызывающего, `sweep` удаляет устаревшие.
 */
export interface InboxStore {
  /**
   * Отмечает сообщение обработанным транзакцией вызывающего.
   *
   * Транзакция приходит непрозрачным значением: её тип объявляет
   * приложение, и пакет не вызывает на ней ни одного метода.
   *
   * Разрешение гонки принадлежит хранилищу: две реплики, получившие одно
   * сообщение, обязаны дать ровно одну обработку. Конфликт уникальности
   * при этом не рвёт транзакцию вызывающего — она остаётся пригодной для
   * коммита.
   *
   * @param transaction - Значение переменной транзакции из контекста
   * @param mark - Потребитель, ключ идемпотентности и момент
   * @returns `'claimed'` у первой доставки, `'duplicate'` у повтора
   */
  claim(transaction: unknown, mark: InboxMark): Promise<InboxClaim>;

  /**
   * Удаляет отметки старше срока хранения.
   *
   * Работает собственным соединением, вне транзакции запроса: уборщик
   * живёт в фоне и транзакции не имеет.
   *
   * @returns Сколько отметок удалено
   */
  sweep(options: InboxSweepOptions): Promise<number>;
}
