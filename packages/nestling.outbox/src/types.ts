/**
 * Запись outbox'а и интерфейс её хранилища.
 *
 * Хранилище — единственное место, которым пакет касается базы данных, и
 * поставляет его приложение. Драйвера здесь нет и не будет: адаптер и
 * транзакция обязаны жить на одном соединении, а пакет, который везёт
 * соединение, перестаёт быть драйвер-независимым.
 */

/**
 * Запись outbox'а: сообщение, отложенное до коммита.
 *
 * Собирается транзакционным эмиттером и доходит до шины неизменной.
 * Идентификатор служит ключом идемпотентности публикации, поэтому повтор
 * доставки узнаётся получателем по нему.
 */
export interface OutboxRecord {
  /** Идентификатор записи; он же ключ идемпотентности публикации */
  readonly id: string;

  /** Subject операции — её имя */
  readonly subject: string;

  /** Проверенный схемой payload */
  readonly payload: unknown;

  /** Долговечность доставки; берётся из операции */
  readonly durable: boolean;

  /**
   * Раздел, внутри которого порядок сохраняется.
   *
   * Записи одного раздела публикуются в порядке создания. Между разделами
   * порядок не гарантируется. Записи без раздела не упорядочены ничем.
   */
  readonly partitionKey?: string;

  /** Момент создания записи, epoch-миллисекунды */
  readonly createdAt: number;

  /**
   * Переданный контекст вызова: значения переменных с `propagate: true`.
   *
   * Едет конвертом, а не payload'ом, — так же, как у обычного `emit`.
   */
  readonly context?: Record<string, unknown>;
}

/**
 * Запись, взятая relay в работу: сама запись плюс счётчик попыток.
 *
 * Счётчик ведёт хранилище: только оно переживает перезапуск процесса.
 */
export interface ClaimedRecord extends OutboxRecord {
  /** Сколько попыток публикации уже провалилось */
  readonly attempts: number;
}

/** Исход публикации одной записи */
export type OutboxSettlement =
  | {
      /** Запись опубликована; повторять её больше не нужно */
      readonly status: 'published';
      readonly id: string;
    }
  | {
      /** Публикация не удалась; запись вернётся в выдачу после `availableAt` */
      readonly status: 'retry';
      readonly id: string;
      /**
       * Новое число провалившихся попыток.
       *
       * Считает relay, а не хранилище: политика повторов принадлежит ему.
       * Запись, до которой очередь раздела не дошла, возвращается с
       * прежним числом — попытки у неё не было.
       */
      readonly attempts: number;
      /** Момент, раньше которого запись не выдаётся, epoch-миллисекунды */
      readonly availableAt: number;
    }
  | {
      /** Попытки исчерпаны; запись больше не выдаётся и ждёт вмешательства */
      readonly status: 'stuck';
      readonly id: string;
    };

/** Аргументы выборки партии */
export interface OutboxClaimOptions {
  /** Сколько записей выдать максимум */
  readonly limit: number;

  /** Текущий момент по часам relay, epoch-миллисекунды */
  readonly now: number;
}

/**
 * Хранилище записей outbox'а. Адаптер поставляет приложение под своим
 * DI-токеном, который принимает плагин полем `store`.
 *
 * Три операции покрывают весь жизненный цикл записи: `append` кладёт её
 * транзакцией вызывающего, `claim` выдаёт партию relay, `settle`
 * отмечает исход.
 */
export interface OutboxStore {
  /**
   * Дописывает записи транзакцией вызывающего.
   *
   * Транзакция приходит непрозрачным значением: её тип объявляет
   * приложение, и пакет не вызывает на ней ни одного метода.
   *
   * @param transaction - Значение переменной транзакции из контекста
   * @param records - Записи одного `emit`
   */
  append(transaction: unknown, records: readonly OutboxRecord[]): Promise<void>;

  /**
   * Выдаёт следующую партию и помечает её взятой в работу.
   *
   * Единственное место интерфейса, отвечающее за конкурентную выборку:
   * реплики разбирают одну таблицу, и партия не должна достаться двум.
   * Адаптер SQL реализует это пропуском заблокированных строк.
   *
   * Порядок раздела обеспечивает выдача: запись с `partitionKey` не
   * выдаётся, пока предыдущая запись того же раздела не отмечена
   * опубликованной или застрявшей.
   *
   * @returns Записи в порядке создания
   */
  claim(options: OutboxClaimOptions): Promise<readonly ClaimedRecord[]>;

  /**
   * Отмечает исходы партии.
   *
   * Идемпотентен: повтор с тем же исходом ничего не меняет. Relay может
   * упасть между публикацией и отметкой, и тогда `settle` получит ту же
   * запись дважды.
   */
  settle(outcomes: readonly OutboxSettlement[]): Promise<void>;
}
