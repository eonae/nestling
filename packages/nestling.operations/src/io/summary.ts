/**
 * Счётчики запроса для наблюдателей (`ctx.summary`).
 *
 * Объект создаётся вместе с контекстом; значения обновляют рантайм
 * item-цепочек (элементы) и транспорт (байты, если он их считает). У
 * непотоковых endpoint'ов счётчики остаются нулями: поле есть всегда, чтобы
 * наблюдателю не приходилось проверять форму.
 */
export interface StreamSummary {
  /** Элементы, дошедшие до хендлера */
  itemsIn: number;

  /** Элементы, отданные наружу */
  itemsOut: number;

  /** Прочитанные байты входа, если транспорт их считает */
  bytesIn?: number;

  /** Записанные байты ответа, если транспорт их считает */
  bytesOut?: number;
}

/** Создаёт пустой итог: вызывается вместе с контекстом запроса */
export function makeSummary(): StreamSummary {
  return { itemsIn: 0, itemsOut: 0 };
}
