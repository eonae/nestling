/**
 * Итог запроса для наблюдателей.
 *
 * Живой объект: ссылка создаётся вместе с контекстом, значения дописывают
 * рантайм цепочек (элементы) и транспорт (байты, где он их знает). Для
 * не-потоковых ручек счётчики остаются нулями — поле есть всегда, чтобы
 * юнит-наблюдатель не ветвился.
 */
export interface StreamSummary {
  /** Элементы, дошедшие до хендлера */
  itemsIn: number;

  /** Элементы, отданные наружу */
  itemsOut: number;

  /** Прочитанные байты входа, если транспорт их считает */
  bytesIn?: number;

  /** Записанные байты ответа, если транспорт их считает */
  bytesOut?: number;
}

/** Создаёт пустой итог: вызывается вместе с контекстом запроса */
export function makeSummary(): StreamSummary {
  return { itemsIn: 0, itemsOut: 0 };
}
