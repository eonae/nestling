import { app } from './app.js';

import { argv } from '@nestlingjs/app';

/**
 * Точка входа: `build()` собирает приложение для этого процесса,
 * `run()` проводит его по фазам. Остановка по `SIGTERM` и `SIGINT`
 * устанавливается автоматически.
 *
 * Состав задают аргументы командной строки: `--docs off` убирает
 * документацию, `--help` печатает схему целиком. Маркер владеет
 * процессом: отказ сборки уходит в `stderr`, и процесс завершается
 * кодом `1`.
 */
await app.build(argv(process.argv)).run();
