/**
 * Фаза приложения — значение, которое читают узлы ядра.
 *
 * Фазовую модель целиком описывает `AssembledApp`: `run()` ведёт
 * приложение `0 BOOTSTRAP → 1 ASSEMBLE → 2 INIT → 3 WIRE → 4 START →
 * 5 RUN`, `close()` переводит его в `6 SHUTDOWN`. Здесь живёт только имя
 * текущей фазы: тип нужен и рантайму, и отчёту пробы, а модуль без
 * импортов не создаёт цикла между слоями.
 */

/**
 * Текущая фаза приложения.
 *
 * Наблюдаемых значений пять: первый узел появляется на INIT, поэтому фаз
 * 0 BOOTSTRAP и 1 ASSEMBLE узел ядра не видит.
 *
 * DI-токена у фазы нет намеренно: инъекция текущей фазы — приглашение
 * ветвиться по ней в прикладном коде, а фазовая модель существует ровно
 * ради того, чтобы такие ветвления были не нужны. Узлам ядра фаза
 * передаётся функцией чтения.
 */
export type AppPhase = 'INIT' | 'WIRE' | 'START' | 'RUN' | 'SHUTDOWN';
