/**
 * Конфигурация клиента и его словарь вызова.
 *
 * Всё, что клиент передаёт **на каждый вызов**, живёт в декларации (`input`
 * плюс bind-карта). Здесь — только то, что общее для всех вызовов: адрес
 * сервиса, ambient-заголовки, читалка трассы и реализация `fetch`.
 */

/**
 * Ambient-заголовки: запись либо функция, вызываемая на каждый запрос.
 *
 * Функция нужна ротируемому Bearer-токену: статическая запись защёлкнула бы
 * его на момент создания клиента, и первый же refresh сделал бы клиента
 * бесполезным.
 */
export type ClientHeaders =
  | Record<string, string>
  | (() => Record<string, string> | Promise<Record<string, string>>);

/** Словарь создания клиента */
export interface ClientConfig {
  /**
   * Абсолютный адрес сервиса. Склеивается с шаблоном пути **буквально**
   * (без хвостового слэша плюс путь) — «умного» разрешения относительных
   * URL нет: адрес в операции и адрес отправленного запроса обязаны
   * совпадать посимвольно.
   */
  baseUrl: string;

  /** Заголовки, общие для всех вызовов (авторизация, трассировка) */
  headers?: ClientHeaders;

  /**
   * Читалка трассы: строка W3C trace-context на каждый запрос или
   * `undefined`, если трассы нет.
   *
   * Клиент сам её не добывает: он зависит только от
   * `@nestlingjs/operations` и собирается для браузера, а трасса живёт в
   * ambient-контексте запроса. Приложение на Nestling передаёт сюда
   * готовую `traceparent` из `@nestlingjs/app`.
   *
   * Заголовок `traceparent`, заданный полем `headers`, сильнее: явное
   * значение конфигурации важнее подставленного.
   *
   * @example
   * ```typescript
   * import { traceparent } from '@nestlingjs/app';
   *
   * const api = makeClient({ getUser: GetUser }, { baseUrl, trace: traceparent });
   * ```
   */
  trace?: () => string | undefined;

  /** Реализация `fetch`; по умолчанию — глобальная */
  fetch?: typeof globalThis.fetch;

  /**
   * Валидировать ли успешный ответ по форме `output` операции.
   *
   * По умолчанию **да**: обещание клиента — типизированный результат, а
   * отдать невалидированный JSON под типом `Output` значит соврать в типе.
   * Отключается явно и однострочно.
   */
  validateOutput?: boolean;
}

/**
 * Словарь вызова — тот же эксплуатационный профиль, что у порта.
 *
 * `idempotencyKey` в v1 нет: согласованного HTTP-слота для него не
 * существует, а провезти его «каким-нибудь заголовком» значит
 * договориться с самим собой.
 */
export interface ClientMeta {
  /** Канал отмены вызова: передаётся в запрос и отменяет его */
  signal?: AbortSignal;

  /**
   * Бюджет вызова — **абсолютный момент**, как у портов. Истёкший бюджет
   * даёт отказ **до** отправки: ходить в сеть за заведомо просроченным
   * ответом незачем.
   */
  deadline?: Date;
}
