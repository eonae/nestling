/**
 * Провозимая ambient-переменная примера.
 *
 * `{ propagate: true }` — свойство **объявления**: провозится именно эта
 * переменная, и решение об этом видно там же, где она объявлена. Общей
 * протечки контекста вызывающего в реализацию не существует — вызов порта
 * открывает собственный request-scope, а `propagate` есть именованное
 * исключение из этого правила.
 */

import { contextVar } from '@nestling/pipeline';

/**
 * Арендатор, от имени которого исполняется цепочка.
 *
 * Кладётся один раз — на входе в процесс-потребитель — и дальше доезжает
 * до реализации в **другом** процессе сам: вызыватель собирает провозимые
 * значения из ячейки текущего запроса и кладёт их в конверт шины.
 */
export const TenantId = contextVar<string>()('tenantId', { propagate: true });
