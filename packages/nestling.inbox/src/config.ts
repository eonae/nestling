/**
 * Секция конфигурации пакета: `INBOX_*`.
 *
 * Наружу отдаются только ключи: DI-токен секции остаётся приватным, и
 * инжектировать её может только этот пакет. Так же устроены секции ядра и
 * транспортов.
 */

import { flag, int } from './schema.js';

import { makeConfig } from '@nestlingjs/app';

/** Срок хранения отметки по умолчанию: семь суток */
const DEFAULT_RETENTION_MS = 7 * 24 * 60 * 60 * 1000;

/**
 * Секция уборщика отметок.
 *
 * Все поля читаются из окружения процесса, а не из аргумента фабрики: в
 * split-развёртывании два процесса поднимают один и тот же плагин с
 * разными значениями.
 *
 * @internal Инжектируется уборщиком; наружу отдаётся `inboxConfigKeys`
 */
export const InboxConfig = makeConfig('inbox', {
  /**
   * Сколько отметка живёт до уборки.
   *
   * Срок обязан перекрывать окно повторов брокера: удалённая отметка
   * перестаёт узнавать повтор, и последняя попытка доставки дойдёт до
   * хендлера второй раз. Окно задаётся конфигурацией потока вне Nestling,
   * поэтому умолчание взято с запасом — семь суток.
   */
  retentionMs: int(DEFAULT_RETENTION_MS, 0),

  /** Пауза между проходами уборщика */
  sweepIntervalMs: int(60_000, 0),

  /** Сколько отметок уборщик удаляет за один проход */
  batchSize: int(500, 1),

  /**
   * Чистит ли таблицу этот процесс.
   *
   * В split-развёртывании отметки ставят все процессы, а чистит их один:
   * две реплики уборщика конкурируют за одну таблицу, и платить этим без
   * нужды незачем.
   */
  sweep: flag(true),
});

/** Ключи секции — то, что пакет отдаёт наружу для `config:` в корне */
export const inboxConfigKeys = InboxConfig.keys;

/** Проекция секции */
export interface InboxConfigValues {
  readonly retentionMs: number;
  readonly sweepIntervalMs: number;
  readonly batchSize: number;
  readonly sweep: boolean;
}
