/**
 * Билдеры полей секций конфигурации — два приёма, которые повторяются везде.
 *
 * Оба возвращают **открытое** значение zod: границу, описание и умолчание
 * дописывает вызывающий цепочкой (`int().min(1).default(500)`). Позиционных
 * аргументов у билдеров нет — они закрыли бы остальные ограничения
 * валидатора и читались бы хуже цепочки.
 *
 * Заменителей тому, что zod уже даёт одним выражением, здесь нет:
 * обязательная непустая строка это `z.string().min(1)`, перечисление —
 * `z.enum([…])`, рекорд полей — `z.object({ … })`.
 */

import { z } from 'zod';

/**
 * Целое число; строка приводится к числу.
 *
 * Приведение нужно всем: значение из окружения приходит строкой, а из
 * объекта в тесте — числом.
 *
 * @returns Открытая схема zod
 *
 * @example
 * ```typescript
 * makeConfig('outbox', { batchSize: int().min(1).default(100) });
 * ```
 */
export const int = () => z.coerce.number().int();

/**
 * Булево значение; строковая запись принимается наравне с ним.
 *
 * `z.stringbool()` понимает `true`/`false`, `1`/`0`, `yes`/`no`, `on`/`off` —
 * ровно то, чем булево поле записывают в окружении.
 *
 * @returns Открытая схема zod
 *
 * @example
 * ```typescript
 * makeConfig('outbox', { relay: flag().default(true) });
 * ```
 */
export const flag = () => z.union([z.boolean(), z.stringbool()]);
