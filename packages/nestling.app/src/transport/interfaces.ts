import type { Dispatch } from './dispatch.js';

import type { Token } from '@nestlingjs/container';

/**
 * DI-токен транспорта: уточнение kernel-типа `TransportRef` до `ITransport`.
 *
 * Транспортный пакет объявляет свой DI-токен именно так; декларации ссылаются
 * на транспорт этим значением, а `App` резолвит по нему инстанс из графа.
 */
export type TransportToken = Token<ITransport>;

/**
 * Базовый интерфейс транспорта.
 *
 * Способностей здесь нет: формы io — данные **объявления**
 * (`TransportDeclaration.capabilities`), потому что проверка форм идёт на
 * фазе ASSEMBLE, где экземпляров ещё нет.
 */
export interface ITransport {
  /**
   * Начинает приём запросов этим транспортом.
   *
   * Единственный вход: нульарного `listen()` и точки регистрации отдельного
   * endpoint'а в операции нет. Всё, чем транспорт обслуживает запросы,
   * передаётся `dispatch`'ем — а он существует только с фазы WIRE, поэтому
   * «начать принимать запросы при захвате» бесполезно: маршрутизировать
   * было бы нечего.
   *
   * @param dispatch - Маршруты этого транспорта и исполнение endpoint'а
   * @param signal - Канал остановки: взвод означает «новые запросы не
   * принимаются, in-flight отменяются кооперативно»
   */
  serve(dispatch: Dispatch, signal: AbortSignal): Promise<void>;

  /**
   * Останавливает транспорт (дренаж соединений с таймаутом).
   *
   * Второй канал остановки рядом с `signal`: сигнал отменяет работу,
   * `close()` отпускает ресурсы.
   */
  close?(): Promise<void>;
}

/**
 * DI-токен сервера: уточнение kernel-типа до `IListener`.
 *
 * Пакет, объявляющий сервер, называет свой DI-токен именно так; `App`
 * резолвит по нему экземпляр из графа, чтобы позвать `listen` и `drain`.
 */
export type ServerToken = Token<IListener>;

/**
 * Слушатель: узел графа, который владеет сокетом.
 *
 * Ядро знает роль, а не протокол: ни `node:http`, ни `net` в
 * `@nestlingjs/app` не входят. Реализация живёт в транспортном пакете
 * (`HttpServer` в `@nestlingjs/transport.http`), а корень отвечает только за
 * порядок шагов: `listen` — последний шаг START, `drain` — первый шаг
 * SHUTDOWN.
 *
 * Слушатель заодно ресурс: экземпляр создаётся на INIT и освобождается в
 * `destroy()` контейнера. Роли делят обязанности по фазам, поэтому шагов
 * остановки два, и путать их нельзя (см. `drain`).
 */
export interface IListener {
  /**
   * Открывает сокет.
   *
   * Зовётся последним шагом START — после `serve` **всех** транспортов.
   * До этого момента сокета нет вовсе, поэтому запрос не может прийти
   * раньше, чем обработчики присоединены.
   */
  listen(): Promise<void>;

  /**
   * Перестаёт принимать соединения и дочитывает открытые.
   *
   * Шаг реверса START, а не освобождение ресурса: `drain()` идёт **до**
   * `close()` транспортов, а `release()` — последним, вместе с прочими
   * ресурсами в `destroy()` контейнера. Два шага нужны потому, что
   * серверы обязаны перестать принимать соединения раньше, чем закроются
   * транспорты.
   */
  drain(): Promise<void>;
}
